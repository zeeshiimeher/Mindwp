/**
 * REPUTATION & REVIEW SYSTEMS REBUILD BRIEF — MindWP
 *
 * Purpose:
 * Help an established service business or specialist clinic recognise that good
 * work is already happening, but too little of it becomes visible trust. Review
 * requests, feedback routing, response ownership, proof capture, and proof
 * placement should not depend on staff memory, luck, or scattered habits.
 *
 * This page should make clear that Reputation & Review Systems is a serious
 * commercial service, but not a generic reputation-management page, review
 * software setup, review widget offer, fake-review/review-gating system,
 * dashboard product, or “get more 5-star reviews” pitch. Public language should
 * sell the operating path and trust outcome, not the backend platform.
 *
 * Page role:
 * Reputation & Review Systems is a primary service page and BOFU decision-
 * support page. It owns review request timing, request sequences, channel logic,
 * feedback routing, response ownership, review visibility, proof capture,
 * website proof placement direction, local trust support, and improvement
 * signals from feedback.
 *
 * It may reference Smart Website Systems, Local SEO Authority Systems, Lead
 * Response & Handling Systems, and Follow-Up & CRM Systems only where they
 * clarify the review/proof path. It must not absorb website rebuild scope, full
 * local SEO operations, first-response handling, full CRM lifecycle, or broad
 * automation positioning.
 *
 * Audience reality:
 * - Service businesses: completed jobs, maintenance visits, quotes, repeat work,
 *   customer experience, review requests, private feedback, local trust, proof,
 *   and staff remembering or forgetting to ask.
 * - Specialist clinics: appointments, consultations, patient experience,
 *   appropriate follow-up, reviews, provider/practice trust, and proof — without
 *   medical claims, treatment-result claims, patient outcome claims, compliance
 *   claims, EMR/software framing, or generic doctor marketing.
 *
 * Page length and section direction:
 * This should be a substantial service page because reputation workflows are a
 * real high-value service. It needs enough depth to show review request timing,
 * feedback routing, response ownership, proof capture, proof placement, fit,
 * hesitation, and a diagnostic CTA without sounding like review software or a
 * platform reseller.
 *
 * The section sequence below is strategic direction, not a rigid wireframe or
 * final section count. Claude may merge, split, rename, reorder, or reshape
 * sections if the service-page argument becomes stronger, but the final page
 * should still feel complete, premium, commercially serious, and specific to
 * Reputation & Review Systems.
 *
 * Soft section direction:
 * 1. Hero — Good Work Happens. Too Little Becomes Visible Trust.
 *    Open with buyer/practice recognition, not “we get you more reviews.” Show
 *    completed jobs, appointments, satisfied customers/patients, inconsistent
 *    review requests, scattered proof, and unmanaged feedback moments.
 *
 * 2. Most Businesses Do Not Have a Review Problem. They Have a Review-System Problem.
 *    Carry forward the strong old-page idea. The real issue is usually timing,
 *    ownership, channel choice, routing, follow-up, response discipline, and
 *    proof placement — not simply that customers never had good experiences.
 *
 * 3. Reputation Is Not Stars, Widgets, or Review Volume.
 *    Reframe the category. Contrast star ratings/widgets/platform dashboards
 *    with request timing, feedback routing, proof capture, response ownership,
 *    and local trust support.
 *
 * 4. Where Reviews and Proof Usually Break.
 *    Build a leak map: job/appointment completed, nobody asks, request sent too
 *    late, unhappy feedback goes unmanaged, good proof stays unused, reviews do
 *    not support local trust or website decisions.
 *
 * 5. What Reputation & Review Systems Owns.
 *    Define ownership clearly: review request timing, request sequences, message
 *    and channel logic, feedback routing, response ownership, monitoring/review
 *    visibility, proof capture, website proof placement direction, local trust
 *    support, and improvement signals.
 *
 *    Also show what it does not replace: fake reviews, review manipulation,
 *    review gating, guaranteed review volume, guaranteed ratings, full Local SEO,
 *    full Smart Website rebuilds, full CRM lifecycle, broad automation, medical
 *    outcome claims, or patient-result claims.
 *
 * 6. The Right Request at the Right Moment.
 *    Make the system concrete. For service businesses: job completed, experience
 *    confirmed, request sent, follow-up if appropriate, proof captured. For
 *    clinics: appointment/consultation/patient experience, appropriate follow-up,
 *    feedback/review path, and trust-sensitive proof. No medical outcomes.
 *
 * 7. Feedback Routing Protects Trust.
 *    Separate feedback routing from review asking. Show three ethical paths:
 *    positive experience -> review path, private concern -> internal owner, and
 *    repeated pattern -> improvement signal. Avoid “suppress bad reviews” or
 *    review-gating language.
 *
 * 8. Review Automation Without Over-Chasing.
 *    Give review automation the commercial weight it deserves without vendor or
 *    platform language. Show trigger moments, timing rules, SMS/email path where
 *    relevant, reminders with stop conditions, channel choice, owner visibility,
 *    and avoiding spammy over-chasing.
 *
 * 9. Reviews and Proof Should Support Local Visibility and the Website.
 *    Connect to other systems without absorbing them. Reputation & Review
 *    Systems captures and routes proof. Smart Website Systems places proof inside
 *    the website path. Local SEO Authority aligns proof with local verification.
 *
 * 10. What Changes When Review and Feedback Paths Are Owned.
 *     Show operating change without fake metrics: request moments are defined,
 *     feedback has a route, response ownership is visible, proof supports
 *     decisions, and repeated patterns become easier to improve.
 *
 * 11. How This Shows Up in Service Businesses and Specialist Clinics.
 *     Use realistic scenario cards only if they help: HVAC maintenance visit,
 *     roofing project proof capture, plumbing feedback routing, tree service real
 *     visual proof, orthodontic parent/patient experience, dental implant
 *     consultation follow-up, dermatology appointment feedback sensitivity, or
 *     hearing-aid after-care/review timing. No fake metrics, medical outcomes,
 *     treatment results, or patient-result claims.
 *
 * 12. Fit / Not Fit.
 *     Good fit: established service businesses and specialist clinics with real
 *     activity, enough customer/patient experience, reviews mattering to trust,
 *     scattered proof, staff forgetting to ask, feedback without an owner, and
 *     local trust affecting enquiries/bookings.
 *
 *     Not fit: fake-review buyers, guaranteed 5-star buyers, review-gating or
 *     manipulation buyers, widget-only buyers, businesses with no meaningful
 *     activity, buyers trying to hide service problems, reputation dashboard demo
 *     buyers, or healthcare buyers expecting medical/compliance/treatment outcome
 *     claims.
 *
 * 13. FAQ.
 *     Use FAQ only for real buying hesitation: whether this is review management
 *     software, whether reviews are guaranteed, how feedback routing works, where
 *     reviews/proof appear on the website, how this connects to GBP/local trust,
 *     whether it works with existing CRM/follow-up, and what happens with
 *     negative feedback.
 *
 * 14. Final Diagnostic CTA.
 *     Close with a practical review of the review, feedback, and proof path. The
 *     CTA should feel useful and diagnostic, not like a “get more reviews” pitch,
 *     review software demo, platform setup quote, sales push, or generic contact
 *     form.
 *
 * Component and content guidance:
 * - Use HeroFrame for the service hero if it helps the page argument.
 * - Use SectionShell as the outer wrapper for major sections where useful.
 * - Use page-owned JSX for proof paths, review-system problem contrasts, review
 *   and proof leak maps, ownership boundaries, timing boards, feedback-routing
 *   surfaces, automation-without-over-chasing panels, proof-placement maps,
 *   before/after operating states, scenario boards, and fit filters.
 * - Do not force all section content into the data file while the page is being
 *   proven. Hero, FAQ, and DecisionPanel content may stay in data if useful.
 * - Use DecisionPanel for the final diagnostic CTA if it fits.
 * - Use FAQSection only if the questions answer real buying hesitation.
 * - Do not let old renderer order, existing data shape, or reusable components
 *   force generic review cards, star-rating grids, dashboard mockups, process
 *   steps, or weak section rhythm.
 *
 * Visual direction:
 * Calm, premium, operational, specific, and commercially serious. Use completed
 * work -> feedback/review -> proof -> trust paths, review timing boards,
 * feedback routing surfaces, proof placement maps, ownership maps, before/after
 * proof-state panels, ethical fit filters, selective scenario/proof surfaces,
 * and diagnostic CTA panels.
 *
 * This page should feel visually distinct from Smart Website Systems and Local
 * SEO Authority. SWS uses website-control maps, service-page anatomy, handoff
 * paths, and implementation pathways. Local SEO uses find -> verify -> trust ->
 * contact, GBP/website alignment, service-area relevance, and local proof. This
 * page should use review timing, feedback routing, proof capture, proof
 * placement, and trust-support surfaces.
 *
 * Selective imagery is allowed when it supports business meaning. Avoid random
 * stock photos, fake dashboards, SaaS UI, AI robot visuals, generic laptop
 * mockups, decorative charts, generic star-rating walls, fake testimonial grids,
 * review-growth dashboards, and image-heavy gallery behavior.
 *
 * CTA posture:
 * Diagnostic, low-pressure, practical.
 *
 * Good directions:
 * - Review my proof and reviews
 * - Check my review path
 * - Find where proof is being missed
 * - Request a reputation system review
 *
 * Simple UI labels may work only when nearby copy explains the diagnostic value.
 *
 * Avoid:
 * Generic reputation-management page, review software page, fake review offer,
 * review-gating language, “get more 5-star reviews” pitch, review velocity as
 * the core promise, SEO reviews-as-ranking-hack framing, testimonial-heavy fake
 * proof, SaaS dashboard imitation, platform/reseller language, AI review-response
 * hype, fake proof, fake metrics, unsupported medical/treatment claims, patient
 * result claims, and old renderer order.
 *
 * Rebuild instruction:
 * Existing JSX and old Reputation/Review content are context only. Preserve
 * useful intent, not old structure. The old files had useful ideas — review
 * request workflow, negative/private feedback routing, review monitoring and
 * response ownership, trust as a conversion bottleneck, and review automation as
 * timing/routing discipline — but they can drift toward platform setup,
 * reputation software, dashboard language, and review-growth promises. Carry
 * forward the commercial substance in current MindWP language.
 *
 * First create the render shape: HeroFrame setup, SectionShell sequence,
 * section titles/descriptions/tone, CTA placement, and any needed custom class
 * or background-treatment decisions.
 *
 * Then design the inner section content with page-owned JSX.
 *
 * Since this page comes after the first-three-pages baseline, shared component,
 * token, or CSS changes should be treated as requiring explicit user approval
 * unless the user has opened a design-system change task. Report page-owned
 * changes, shared component changes, token/CSS changes, and design-system
 * implications separately.
 */
import { ArrowRight, FileText, Inbox, PhoneOff } from 'lucide-react';

import { FAQSection } from '@/components/content/FAQSection';
import { DecisionPanel } from '@/components/conversion/DecisionPanel';
import { HeroFrame } from '@/components/layout/HeroFrame';
import { SectionShell } from '@/components/layout/SectionShell';
import { StatusBadge } from '@/components/primitives/StatusBadge';
import type { ServicePageData } from '@/domains/services/types';

interface Props {
  data: ServicePageData;
  slug: string;
}

export default function ReputationReviewSystemsRenderer({ data }: Props) {
  const { hero, cta } = data;
  const faq = data.faq;

  return (
    <main>
      <ReputationReviewSystemsHero hero={hero} ctaHref={cta.actions[0]?.href ?? '/contact'} />
      <ReputationReviewSystemsRecognitionSection />
      {faq ? <ReputationReviewSystemsFAQ faq={faq} /> : null}
      <ReputationReviewSystemsDecisionPanel cta={cta} />
    </main>
  );
}

function ReputationReviewSystemsHero({
  hero,
  ctaHref,
}: {
  hero: Props['data']['hero'];
  ctaHref: string;
}) {
  return (
    <HeroFrame
      ariaLabel='Reputation & Review Systems hero'
      eyebrow={hero.eyebrow}
      title={hero.title}
      description={hero.description}
      actions={[
        {
          label: 'Request a System Review',
          href: ctaHref,
          variant: 'white',
          icon: <ArrowRight size={16} aria-hidden='true' />,
        },
      ]}
      chips={Array.isArray(hero.list) ? hero.list.map(label => ({ label })) : undefined}
      chipDotVariant='subtle'
      visual={<ReputationReviewSystemsSignalPanel visual={hero.visual} />}
    />
  );
}

function ReputationReviewSystemsSignalPanel({
  visual,
}: {
  visual: Props['data']['hero']['visual'];
}) {
  if (!visual) return null;

  return (
    <div className='rounded-[var(--mw-radius-2xl)] border border-[var(--mw-white-12)] bg-[var(--mw-white-06)] p-5 shadow-[var(--mw-shadow-dark-lg)]'>
      <div className='mb-5 flex items-start justify-between gap-4 border-b border-[var(--mw-white-10)] pb-4'>
        <div>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>{visual.title}</p>
          <p className='mw-text-on-dark-muted'>{visual.subtitle}</p>
        </div>
        <StatusBadge variant='active' label='Live' />
      </div>

      <div className='grid gap-3'>
        {visual.rows.map(row => {
          const status = String(row.status);
          const Icon =
            status === 'leaking' || status === 'risk'
              ? PhoneOff
              : status === 'unowned' || status === 'warn'
                ? FileText
                : Inbox;
          const badgeVariant =
            status === 'leaking' || status === 'risk'
              ? 'leaking'
              : status === 'unowned' || status === 'warn'
                ? 'unowned'
                : 'handled';

          return (
            <div
              key={row.label}
              className='grid grid-cols-[auto_1fr_auto] items-center gap-3 rounded-[var(--mw-radius-lg)] border border-[var(--mw-white-08)] bg-[var(--mw-white-04)] px-3 py-3'
            >
              <span className='grid size-8 place-items-center rounded-full border border-[var(--mw-white-12)] bg-[var(--mw-white-08)] text-[var(--mw-signal-cyan)]'>
                <Icon size={15} aria-hidden='true' />
              </span>
              <strong className='mw-text-on-dark'>{row.label}</strong>
              <StatusBadge variant={badgeVariant} label={row.value} />
            </div>
          );
        })}
      </div>

      <div className='mt-5 flex flex-wrap items-center gap-3 border-t border-[var(--mw-white-10)] pt-4'>
        <StatusBadge variant='handled' label={visual.footerPrimary} />
        <StatusBadge variant='active' label={visual.footerSecondary} />
      </div>
    </div>
  );
}

