/**
 * FOLLOW-UP & CRM SYSTEMS REBUILD BRIEF — MindWP
 *
 * Purpose:
 * Help an established service business or specialist clinic recognise that the
 * first reply is not enough if nobody owns the next step. Enquiries may be
 * answered, quotes may be sent, consultations may be discussed, and appointments
 * may be requested — but follow-up still slips when ownership, status, reminders,
 * and next steps are not visible.
 *
 * This page is the CRM page in commercial reality. Many buyers already know what
 * a CRM is, and many are actively willing to add one to their business or
 * practice. The page should not hide from that. But MindWP must frame CRM as a
 * practical operating system for ownership, status, next steps, reminders, quote
 * follow-up, consultation follow-up, repeat/rebook paths, and visibility — not as
 * a generic CRM setup, software reseller page, dashboard demo, or tool-first
 * implementation offer.
 *
 * Page role:
 * Follow-Up & CRM Systems is a primary service page and BOFU decision-support
 * page. It owns ownership visibility, enquiry/customer/patient status, next-step
 * tracking, quote follow-up, consultation follow-up, reminders, CRM structure,
 * pipeline/status design, task visibility, repeat/rebook paths where relevant,
 * the handoff after first response, and follow-up visibility.
 *
 * It may reference Smart Website Systems, Lead Response & Handling Systems,
 * Local SEO Authority Systems, and Reputation & Review Systems only where they
 * clarify the follow-up path. It must not absorb website rebuild scope, first-
 * response/missed-call handling, full local SEO operations, full review request
 * and proof-capture ownership, enterprise CRM consulting, or broad automation
 * positioning.
 *
 * Boundary with Lead Response & Handling:
 * Lead Response & Handling answers: did the enquiry get captured, acknowledged,
 * routed, and handed off properly?
 *
 * Follow-Up & CRM answers: after the first response exists, does the enquiry
 * have an owner, status, reminder, next step, quote follow-up, consultation
 * follow-up, or repeat/rebook path?
 *
 * Keep this timing boundary clear in copy, visuals, CTAs, and section structure.
 *
 * Audience reality:
 * - Service businesses: quotes sent, estimates pending, jobs booked or not yet
 *   booked, customers asking follow-up questions, staff using inboxes/spreadsheets
 *   and memory, repeat service reminders, owner visibility, and stuck enquiries.
 * - Specialist clinics: consultation requests, appointment bookings, patient
 *   questions, consultation follow-up, treatment/procedure enquiry status,
 *   reminders, rebooking/after-care paths where appropriate, and practice-team
 *   visibility — without medical claims, treatment-result claims, patient outcome
 *   claims, compliance claims, EMR/practice-management software framing, or
 *   generic doctor marketing.
 *
 * Page length and section direction:
 * This should be a substantial service page because CRM/follow-up visibility is
 * a real high-value service. It needs enough depth to show why ownership becomes
 * invisible, how CRM should match the real working path, where follow-up breaks,
 * why status language matters, how quotes and consultations are followed up, how
 * reminders support the team, how repeat/rebook paths connect, and why a
 * diagnostic CRM/follow-up review is useful.
 *
 * The section sequence below is strategic direction, not a rigid wireframe or
 * final section count. Claude may merge, split, rename, reorder, or reshape
 * sections if the service-page argument becomes stronger, but the final page
 * should still feel complete, premium, commercially serious, and specific to
 * Follow-Up & CRM Systems.
 *
 * Soft section direction:
 * 1. Hero — The Enquiry Was Answered. Then the Follow-Up Disappeared.
 *    Open after first response: someone replied, a quote was sent, a consultation
 *    was discussed, a booking was requested, a patient/customer asked a follow-up
 *    question, but nobody can reliably see the current status or next step.
 *
 * 2. Follow-Up Fails When Ownership Is Invisible.
 *    Show everyday operational pain: inboxes hold conversations, spreadsheets
 *    track some things, staff remember some follow-ups, quotes disappear after
 *    being sent, consultation requests go quiet, and reminders live in someone's
 *    head.
 *
 * 3. CRM Is Useful Only When It Reflects the Real Working Path.
 *    Treat CRM as familiar and commercially valuable, but not as the product by
 *    itself. A CRM should match how enquiries arrive, who responds, how quotes or
 *    consultations are followed up, what statuses mean, and what the team needs
 *    to see. Avoid generic pipeline screenshots or SaaS dashboard imitation.
 *
 * 4. Where Follow-Up Usually Breaks.
 *    Build a follow-up leak map: first reply sent, quote not followed up,
 *    consultation request not owned, appointment not confirmed, customer/patient
 *    asks another question, no reminder, status unclear, and next step depends on
 *    memory.
 *
 * 5. What Follow-Up & CRM Systems Owns.
 *    Define ownership clearly: owner visibility, status, next-step tracking,
 *    quote follow-up, consultation follow-up, reminders, CRM structure,
 *    pipeline/status design, task visibility, repeat/rebook paths where relevant,
 *    handoff after first response, and follow-up reporting/visibility.
 *
 *    Also show what it does not replace: first response/missed-call handling,
 *    full website conversion, full Local SEO, full review generation, fake
 *    automation, full sales-team management, EMR/practice-management software,
 *    medical operations, or compliance operations.
 *
 * 6. Status Should Mean Something the Team Can Act On.
 *    Make CRM concrete. Statuses should be business/practice-specific, not
 *    generic software labels. Examples: new enquiry, contacted, quote sent,
 *    follow-up due, booked, completed, review/proof ready, repeat/reminder due;
 *    or for clinics: consultation requested, contacted, appointment booked,
 *    consultation completed, follow-up needed, enquiry pending, review/proof
 *    appropriate, rebooking/after-care reminder.
 *
 * 7. Quotes and Consultations Need a Follow-Up Path.
 *    This is a major commercial section. Show estimate/quote follow-up,
 *    consultation follow-up, decision pending, booking path, lost/no-response
 *    reason where known, and next-step ownership. For clinics, keep language
 *    around consultation and treatment/procedure enquiry follow-up careful and
 *    free of medical outcome claims.
 *
 * 8. Reminders Should Support the Team, Not Annoy the Customer or Patient.
 *    Explain automation gently. Show staff task reminders, quote follow-up timing,
 *    appointment reminders, maintenance/rebooking reminders, customer/patient
 *    reminders where appropriate, stop conditions, and owner visibility. Avoid
 *    spammy sequences and generic automation-workflow language.
 *
 * 9. Follow-Up Should Connect Back to Proof and Repeat Value.
 *    Connect to Reputation & Review Systems without absorbing it. Follow-Up &
 *    CRM owns status, reminders, next steps, rebooking/repeat paths, and completed
 *    work visibility. Reputation & Review Systems owns review request, feedback
 *    routing, and proof capture.
 *
 * 10. What Changes When Follow-Up Is Visible.
 *     Show operating change without fake metrics: every enquiry has owner/status/
 *     next step, quote and consultation follow-up is visible, reminders support
 *     the team, stuck items are easier to see, handoffs are clearer, and repeat/
 *     rebooking moments are less random.
 *
 * 11. How This Shows Up in Service Businesses and Specialist Clinics.
 *     Use realistic scenario cards only if they help: roofing quote follow-up,
 *     HVAC maintenance reminders, plumbing estimate status, septic repeat service
 *     reminder, tree service estimate follow-up, foundation inspection follow-up,
 *     dental implant consultation follow-up, orthodontic treatment enquiry
 *     follow-up, dermatology appointment follow-up, ENT/sinus consultation
 *     request follow-up, hearing-aid after-care/reminder path, or physiotherapy
 *     appointment/rebooking path. No fake metrics, medical outcomes, treatment
 *     results, or patient-result claims.
 *
 * 12. Fit / Not Fit.
 *     Good fit: established service businesses and specialist clinics where
 *     enquiries already come in, quotes/consultations/bookings need follow-up,
 *     staff rely on inboxes/spreadsheets/memory, the owner cannot see what is
 *     stuck, CRM exists but is not trusted or used properly, and repeat/rebooking/
 *     reminder paths matter.
 *
 *     Not fit: CRM-software-only buyers, generic dashboard demo buyers, full
 *     sales-team consulting buyers, aggressive sales-automation buyers, platform
 *     reseller buyers, businesses with no meaningful enquiry or follow-up
 *     activity, or healthcare buyers expecting EMR/practice-management software,
 *     compliance claims, or treatment outcome promises.
 *
 * 13. FAQ.
 *     Use FAQ only for real buying hesitation: whether this is CRM setup, whether
 *     a new CRM is needed, whether it can work with the existing process, how it
 *     differs from Lead Response & Handling, what follow-up can be automated, how
 *     spammy reminders are avoided, how this works for clinics, and whether it
 *     includes review requests.
 *
 * 14. Final Diagnostic CTA.
 *     Close with a practical review of the CRM and follow-up path. The CTA should
 *     feel useful and diagnostic, not like a CRM software demo, platform setup
 *     quote, aggressive sales automation pitch, or generic contact form.
 *
 * Component and content guidance:
 * - Use HeroFrame for the service hero if it helps the page argument.
 * - Use SectionShell as the outer wrapper for major sections where useful.
 * - Use page-owned JSX for owner/status/next-step paths, invisible-ownership
 *   boards, CRM reality maps, follow-up leak maps, ownership boundaries, status
 *   boards, quote/consultation follow-up paths, reminder logic boards,
 *   completed-work next-step maps, before/after CRM visibility panels, scenario
 *   boards, and fit filters.
 * - Do not force all section content into the data file while the page is being
 *   proven. Hero, FAQ, and DecisionPanel content may stay in data if useful.
 * - Use DecisionPanel for the final diagnostic CTA if it fits.
 * - Use FAQSection only if the questions answer real buying hesitation.
 * - Do not let old renderer order, existing data shape, or reusable components
 *   force generic CRM cards, SaaS dashboard layouts, sales-funnel graphics,
 *   process steps, automation workflow diagrams, or weak section rhythm.
 *
 * Visual direction:
 * Calm, premium, operational, specific, and commercially serious. Use enquiry
 * answered -> owner -> status -> next step -> reminder -> outcome paths,
 * ownership boards, status boards, quote/consultation follow-up paths, reminder
 * logic boards, CRM reality maps, stuck-item boards, completed-work next-step
 * maps, before/after CRM visibility panels, scenario boards, fit filters, and
 * diagnostic CTA panels.
 *
 * This page should feel visually distinct from Lead Response & Handling. Lead
 * Response uses call/form/message -> acknowledgement -> routing -> first owner.
 * Follow-Up & CRM should use owner -> status -> next step -> reminder -> outcome.
 *
 * Selective imagery is allowed when it supports business meaning. Avoid random
 * stock photos, fake dashboards, SaaS UI, AI robot visuals, generic laptop
 * mockups, decorative charts, generic CRM product screenshots, generic pipeline
 * UI, sales funnel graphics, automation workflow spaghetti, and image-heavy
 * gallery behavior.
 *
 * CTA posture:
 * Diagnostic, low-pressure, practical.
 *
 * Good directions:
 * - Review my follow-up path
 * - Check my CRM visibility
 * - Find where follow-up is slipping
 * - Request a CRM and follow-up review
 *
 * Simple UI labels may work only when nearby copy explains the diagnostic value.
 *
 * Avoid:
 * Generic CRM setup page, CRM reseller page, pipeline software demo, SaaS
 * dashboard page, automation workflow page, “we build your sales funnel” page,
 * full lead-response page, call-handling page, review-request page, enterprise
 * CRM consulting page, healthcare EMR/practice-management software page, fake
 * proof, fake metrics, guaranteed revenue claims, unsupported medical/treatment
 * claims, patient-result claims, and old renderer order.
 *
 * Rebuild instruction:
 * Existing JSX and old Follow-Up/CRM content are context only. Preserve useful
 * intent, not old structure. The current renderer still leans toward website
 * handoff and Smart Website language; rebuild it around CRM visibility,
 * ownership, status, next steps, reminders, quote/consultation follow-up, repeat/
 * rebook paths, and the handoff after first response.
 *
 * First create the render shape: HeroFrame setup, SectionShell sequence,
 * section titles/descriptions/tone, CTA placement, and any needed custom class
 * or background-treatment decisions.
 *
 * Then design the inner section content with page-owned JSX.
 *
 * Since this page comes after the first-three-pages baseline, shared component,
 * token, or CSS changes should be treated as requiring explicit user approval
 * unless the user has opened a design-system change task. Report page-owned
 * changes, shared component changes, token/CSS changes, and design-system
 * implications separately.
 */
import { ArrowRight, FileText, Inbox, PhoneOff } from 'lucide-react';

import { FAQSection } from '@/components/content/FAQSection';
import { DecisionPanel } from '@/components/conversion/DecisionPanel';
import { HeroFrame } from '@/components/layout/HeroFrame';
import { SectionShell } from '@/components/layout/SectionShell';
import { StatusBadge } from '@/components/primitives/StatusBadge';
import type { ServicePageData } from '@/domains/services/types';

interface Props {
  data: ServicePageData;
  slug: string;
}

export default function FollowUpCRMRenderer({ data }: Props) {
  const { hero, cta } = data;
  const faq = data.faq;

  return (
    <main>
      <FollowUpCrmHero hero={hero} ctaHref={cta.actions[0]?.href ?? '/contact'} />
      <FollowUpCrmRecognitionSection />
      {faq ? <FollowUpCrmFAQ faq={faq} /> : null}
      <FollowUpCrmDecisionPanel cta={cta} />
    </main>
  );
}

function FollowUpCrmHero({ hero, ctaHref }: { hero: Props['data']['hero']; ctaHref: string }) {
  return (
    <HeroFrame
      ariaLabel='Follow-Up CRM hero'
      eyebrow={hero.eyebrow}
      title={hero.title}
      description={hero.description}
      actions={[
        {
          label: 'Request a System Review',
          href: ctaHref,
          variant: 'white',
          icon: <ArrowRight size={16} aria-hidden='true' />,
        },
      ]}
      chips={Array.isArray(hero.list) ? hero.list.map(label => ({ label })) : undefined}
      chipDotVariant='subtle'
      visual={<FollowUpCrmSignalPanel visual={hero.visual} />}
    />
  );
}

function FollowUpCrmSignalPanel({ visual }: { visual: Props['data']['hero']['visual'] }) {
  if (!visual) return null;

  return (
    <div className='rounded-[var(--mw-radius-2xl)] border border-[var(--mw-white-12)] bg-[var(--mw-white-06)] p-5 shadow-[var(--mw-shadow-dark-lg)]'>
      <div className='mb-5 flex items-start justify-between gap-4 border-b border-[var(--mw-white-10)] pb-4'>
        <div>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>{visual.title}</p>
          <p className='mw-text-on-dark-muted'>{visual.subtitle}</p>
        </div>
        <StatusBadge variant='active' label='Live' />
      </div>

      <div className='grid gap-3'>
        {visual.rows.map(row => {
          const status = String(row.status);
          const Icon =
            status === 'leaking' || status === 'risk'
              ? PhoneOff
              : status === 'unowned' || status === 'warn'
                ? FileText
                : Inbox;
          const badgeVariant =
            status === 'leaking' || status === 'risk'
              ? 'leaking'
              : status === 'unowned' || status === 'warn'
                ? 'unowned'
                : 'handled';

          return (
            <div
              key={row.label}
              className='grid grid-cols-[auto_1fr_auto] items-center gap-3 rounded-[var(--mw-radius-lg)] border border-[var(--mw-white-08)] bg-[var(--mw-white-04)] px-3 py-3'
            >
              <span className='grid size-8 place-items-center rounded-full border border-[var(--mw-white-12)] bg-[var(--mw-white-08)] text-[var(--mw-signal-cyan)]'>
                <Icon size={15} aria-hidden='true' />
              </span>
              <strong className='mw-text-on-dark'>{row.label}</strong>
              <StatusBadge variant={badgeVariant} label={row.value} />
            </div>
          );
        })}
      </div>

      <div className='mt-5 flex flex-wrap items-center gap-3 border-t border-[var(--mw-white-10)] pt-4'>
        <StatusBadge variant='handled' label={visual.footerPrimary} />
        <StatusBadge variant='active' label={visual.footerSecondary} />
      </div>
    </div>
  );
}

function FollowUpCrmRecognitionSection() {
  return (
    <SectionShell
      id='website-handoff'
      ariaLabel='Where websites usually fail'
      tone='mist'
      heading={{
        eyebrow: 'Where websites usually fail',
        title: 'The page looks fine. [[muted:The enquiry has nowhere reliable to go.]]',
        description:
          'A smart website does more than present services. It gives each enquiry a place to land, enough context to be handled, and a clear next step after contact.',
      }}
    >
      <div className='grid gap-5 lg:grid-cols-3'>
        <article className='mw-surface-card p-6'>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>Visitor clarity</p>
          <h3>The visitor understands the offer</h3>
          <p>
            Service pages should answer what the visitor came to check: what you do, who it is for,
            where it is available, and what happens next.
          </p>
        </article>

        <article className='mw-surface-card p-6'>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>Captured with context</p>
          <h3>The enquiry lands somewhere useful</h3>
          <p>
            A form or call should not arrive as a loose message. It should carry source, service,
            location, and enough context for the next person to act.
          </p>
        </article>

        <article className='mw-surface-card p-6'>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>Owned follow-up</p>
          <h3>The next step has an owner</h3>
          <p>
            The difference is not more decoration. It is a visible path from website visit to
            enquiry, response, follow-up, and booked work.
          </p>
        </article>
      </div>
    </SectionShell>
  );
}

function FollowUpCrmFAQ({ faq }: { faq: NonNullable<Props['data']['faq']> }) {
  return (
    <FAQSection
      title={faq.header.title}
      description={faq.header.description}
      items={faq.items.map((item, index) => ({
        id: `follow-up-crm-faq-${index}`,
        question: item.question,
        answer: item.answer,
      }))}
      tone='mist'
      variant='split'
      ariaLabel='Follow-Up CRM FAQ'
    />
  );
}

function FollowUpCrmDecisionPanel({ cta }: { cta: Props['data']['cta'] }) {
  return (
    <DecisionPanel
      heading={{
        title: cta.heading.title,
        subtitle: cta.heading.muted,
        description: cta.heading.description,
      }}
      actions={cta.actions}
      expectations={cta.expectations}
      reassurance={cta.footer}
    />
  );
}

export { FollowUpCRMRenderer };
