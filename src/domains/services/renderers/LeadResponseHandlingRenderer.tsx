/**
 * LEAD RESPONSE & HANDLING REBUILD BRIEF — MindWP
 *
 * Purpose:
 * Help an established service business or specialist clinic recognise that the
 * enquiry is not always the problem. Calls, forms, messages, booking requests,
 * and consultation requests may already come in, but the first response and
 * routing path is weak, delayed, scattered, or unowned.
 *
 * This page should make clear that Lead Response & Handling Systems is not an
 * AI chatbot page, AI receptionist offer, call-center outsourcing page, generic
 * inbox product, CRM setup page, automation workflow page, or lead-management
 * SaaS pitch. It owns the first-response moment: capture, acknowledgement,
 * routing, first ownership, and the first handoff into a visible next step.
 *
 * Page role:
 * Lead Response & Handling Systems is a primary service page and BOFU decision-
 * support page. It owns missed-call recovery, fast acknowledgement, enquiry
 * routing, call handling, form handling, message handling, booking request
 * handling, consultation request handling, after-hours response logic where
 * relevant, and making sure the enquiry lands somewhere useful.
 *
 * It may reference Smart Website Systems, Follow-Up & CRM Systems, Local SEO
 * Authority Systems, and Reputation & Review Systems only where they clarify the
 * first-response path. It must not absorb website rebuild scope, full CRM
 * lifecycle, quote follow-up after first response, full sales pipeline
 * management, full review generation, or broad automation positioning.
 *
 * Boundary with Follow-Up & CRM:
 * Lead Response & Handling answers: did the enquiry get captured, acknowledged,
 * routed, and handed off properly?
 *
 * Follow-Up & CRM answers: after the first response exists, does the enquiry
 * have an owner, status, reminder, next step, quote follow-up, consultation
 * follow-up, or repeat/rebook path?
 *
 * Keep this timing boundary clear in copy, visuals, CTAs, and section structure.
 *
 * Audience reality:
 * - Service businesses: missed calls, forms, quote requests, website messages,
 *   booking requests, busy teams, field staff, after-hours enquiries, urgent or
 *   planned service requests, and customers calling the next provider if nobody
 *   responds.
 * - Specialist clinics: consultation requests, appointment enquiries, callback
 *   requests, booking handoffs, patient trust, staff routing, and follow-up
 *   expectations — without medical claims, emergency-medical promises, treatment-
 *   result claims, patient outcome claims, compliance claims, EMR/software
 *   framing, or generic doctor marketing.
 *
 * Page length and section direction:
 * This should be a substantial service page because first response is a real
 * commercial leak. It needs enough depth to show why people do not wait, where
 * calls/forms/messages break, how channel handling works, why routing matters,
 * how after-hours expectations can be handled responsibly, how the first handoff
 * connects to Follow-Up & CRM, and why a diagnostic review is useful.
 *
 * The section sequence below is strategic direction, not a rigid wireframe or
 * final section count. Claude may merge, split, rename, reorder, or reshape
 * sections if the service-page argument becomes stronger, but the final page
 * should still feel complete, premium, commercially serious, and specific to
 * Lead Response & Handling Systems.
 *
 * Soft section direction:
 * 1. Hero — The Enquiry Came In. The Response Path Was Not Ready.
 *    Open with buyer/practice recognition, not “AI response automation.” Show
 *    calls while the team is busy, forms landing unseen, messages scattered,
 *    booking/consultation requests needing routing, and after-hours enquiries
 *    waiting too long.
 *
 * 2. People Do Not Wait While the Business Gets Organised.
 *    Show urgency without hype: home-service customers may call the next
 *    provider, quote requests lose momentum, and clinic consultation requests
 *    need clear acknowledgement and booking/follow-up expectations.
 *
 * 3. The First Response Breaks in Predictable Places.
 *    Build a first-response leak map: call missed, form unseen, message
 *    scattered, booking request unclear, consultation request not routed,
 *    after-hours enquiry waits, wrong person sees it, or no one owns the first
 *    reply.
 *
 * 4. What Lead Response & Handling Systems Owns.
 *    Define ownership clearly: missed-call recovery, fast acknowledgement,
 *    enquiry routing, call/form/message handling, booking and consultation
 *    request handling, after-hours response logic where relevant, and the first
 *    handoff into owner/status/next step.
 *
 *    Also show what it does not replace: full CRM lifecycle, quote follow-up
 *    after first response, full sales pipeline management, full review
 *    generation, full website conversion, complete business automation, or AI as
 *    the public product.
 *
 * 5. Calls, Forms, Messages, and Bookings Need Different Handling.
 *    Make the service concrete. Show different contact channels — calls, missed
 *    calls, web forms, quote requests, messages/chat, booking requests,
 *    consultation requests, and after-hours enquiries — each needing capture,
 *    acknowledgement, routing, and first owner/next step.
 *
 * 6. The First Reply Should Give the Enquiry Somewhere to Go.
 *    Explain response beyond speed: confirm the enquiry was received, give the
 *    person confidence someone saw it, carry or ask for useful context, route to
 *    the right next step, and set expectations.
 *
 * 7. Routing Matters as Much as Speed.
 *    Show operational depth. Routing may depend on service requested, location
 *    or service area, urgency, quote vs booking vs consultation, new vs existing
 *    customer/patient, business hours vs after-hours, and clinic/practice context
 *    where relevant. Keep it buyer-readable, not a backend automation chart.
 *
 * 8. After-Hours Handling Without Pretending the Business Is Always Open.
 *    Show responsible handling: acknowledge the enquiry, collect useful context,
 *    route the request, set expectations, and prepare the next business-day
 *    follow-up. For clinics, avoid emergency-medical, triage, diagnosis, or
 *    clinical-response promises.
 *
 * 9. The Handoff Into Follow-Up Must Be Visible.
 *    Connect to Follow-Up & CRM without absorbing it. The first response should
 *    create enough context for follow-up to be owned. Show response/routing
 *    handing off into owner, status, and next step.
 *
 * 10. What Changes When Response Handling Is Owned.
 *     Show operating change without fake metrics: enquiries are acknowledged,
 *     contact paths are routed, urgency/context is visible, the right person sees
 *     the right request, first handoff is clearer, and follow-up starts with
 *     context.
 *
 * 11. How This Shows Up in Service Businesses and Specialist Clinics.
 *     Use realistic scenario cards only if they help: HVAC seasonal calls,
 *     plumbing urgent local search, roofing quote requests, foundation repair
 *     inspection requests, septic booking requests, tree service estimates,
 *     dental implant consultation requests, orthodontic consultation bookings,
 *     dermatology appointment requests, ENT/sinus consultation requests, hearing-
 *     aid callbacks, or physiotherapy appointment enquiries. No fake metrics,
 *     medical outcomes, emergency promises, treatment results, or patient-result
 *     claims.
 *
 * 12. Fit / Not Fit.
 *     Good fit: established service businesses and specialist clinics where
 *     calls/forms/messages already come in, missed response is visible, staff are
 *     busy, after-hours enquiries matter, bookings/consultations/quotes need
 *     routing, and first response affects trust.
 *
 *     Not fit: AI-chatbot-as-the-offer buyers, generic call-center outsourcing
 *     buyers, full CRM/pipeline buyers, guaranteed lead-volume buyers, platform
 *     demo buyers, businesses with no meaningful enquiry activity, or healthcare
 *     buyers expecting emergency medical handling, compliance claims, software
 *     implementation, or treatment outcome promises.
 *
 * 13. FAQ.
 *     Use FAQ only for real buying hesitation: whether this is an AI chatbot,
 *     whether it replaces staff, how missed calls are handled, how forms/messages
 *     are routed, how after-hours expectations work, how clinic requests are
 *     handled without medical claims, and how this connects to Follow-Up & CRM.
 *
 * 14. Final Diagnostic CTA.
 *     Close with a practical review of the response path. The CTA should feel
 *     useful and diagnostic, not like an AI chatbot demo, call-center pitch,
 *     platform setup quote, sales push, or generic contact form.
 *
 * Component and content guidance:
 * - Use HeroFrame for the service hero if it helps the page argument.
 * - Use SectionShell as the outer wrapper for major sections where useful.
 * - Use page-owned JSX for first-response paths, delay-risk boards, response
 *   leak maps, ownership boundaries, channel handling boards, acknowledgement-
 *   to-routing paths, routing decision maps, after-hours response boards,
 *   response-to-follow-up handoff panels, before/after operating states,
 *   scenario boards, and fit filters.
 * - Do not force all section content into the data file while the page is being
 *   proven. Hero, FAQ, and DecisionPanel content may stay in data if useful.
 * - Use DecisionPanel for the final diagnostic CTA if it fits.
 * - Use FAQSection only if the questions answer real buying hesitation.
 * - Do not let old renderer order, existing data shape, or reusable components
 *   force generic cards, chatbot bubbles, inbox product UI, process steps,
 *   automation diagrams, or weak section rhythm.
 *
 * Visual direction:
 * Calm, premium, operational, specific, and commercially serious. Use call/form/
 * message/booking request -> acknowledgement -> routing -> first owner paths,
 * missed-call recovery paths, channel handling boards, routing decision maps,
 * after-hours response boards, response-to-follow-up handoff panels, before/after
 * response-state panels, scenario boards, fit filters, and diagnostic CTA panels.
 *
 * This page should feel visually distinct from Smart Website Systems, Local SEO
 * Authority, and Reputation & Review Systems. SWS uses website-control maps and
 * service-page anatomy. Local SEO uses find -> verify -> trust -> contact and
 * local signal boards. Reputation uses completed work -> feedback/review ->
 * proof -> trust. Lead Response should use first-contact, acknowledgement,
 * routing, speed, channel handling, after-hours, and first-handoff surfaces.
 *
 * Selective imagery is allowed when it supports business meaning. Avoid random
 * stock photos, fake dashboards, SaaS UI, AI robot visuals, generic laptop
 * mockups, decorative charts, chatbot-bubble hero as the main idea, call-center
 * imagery, generic inbox product UI, and image-heavy gallery behavior.
 *
 * CTA posture:
 * Diagnostic, low-pressure, practical.
 *
 * Good directions:
 * - Check my response path
 * - Review my missed-call and enquiry handling
 * - Find where enquiries are slipping
 * - Request a response path review
 *
 * Simple UI labels may work only when nearby copy explains the diagnostic value.
 *
 * Avoid:
 * AI chatbot service page, AI receptionist page, SaaS inbox/product page,
 * call-center outsourcing page, CRM setup page, full sales pipeline page,
 * generic automation workflow page, “never miss a lead again” hype, cheap
 * lead-gen language, revenue-recovery framing, fake proof, fake metrics,
 * unsupported medical/treatment claims, emergency medical promises, generic
 * contractor marketing, generic clinic software page, and old renderer order.
 *
 * Rebuild instruction:
 * Existing JSX and old Lead Response content are context only. Preserve useful
 * intent, not old structure. The current renderer still leans toward website
 * handoff and Smart Website language; rebuild it around first response, routing,
 * channel handling, after-hours expectations, and the handoff into Follow-Up &
 * CRM.
 *
 * First create the render shape: HeroFrame setup, SectionShell sequence,
 * section titles/descriptions/tone, CTA placement, and any needed custom class
 * or background-treatment decisions.
 *
 * Then design the inner section content with page-owned JSX.
 *
 * Since this page comes after the first-three-pages baseline, shared component,
 * token, or CSS changes should be treated as requiring explicit user approval
 * unless the user has opened a design-system change task. Report page-owned
 * changes, shared component changes, token/CSS changes, and design-system
 * implications separately.
 */
import { ArrowRight, FileText, Inbox, PhoneOff } from 'lucide-react';

import { FAQSection } from '@/components/content/FAQSection';
import { DecisionPanel } from '@/components/conversion/DecisionPanel';
import { HeroFrame } from '@/components/layout/HeroFrame';
import { SectionShell } from '@/components/layout/SectionShell';
import { StatusBadge } from '@/components/primitives/StatusBadge';
import type { ServicePageData } from '@/domains/services/types';

interface Props {
  data: ServicePageData;
  slug: string;
}

export function LeadResponseHandlingRenderer({ data }: Props) {
  const { hero, cta } = data;
  const faq = data.faq;

  return (
    <main>
      <LeadResponseHandlingHero hero={hero} ctaHref={cta.actions[0]?.href ?? '/contact'} />
      <LeadResponseHandlingRecognitionSection />
      {faq ? <LeadResponseHandlingFAQ faq={faq} /> : null}
      <LeadResponseHandlingDecisionPanel cta={cta} />
    </main>
  );
}

function LeadResponseHandlingHero({
  hero,
  ctaHref,
}: {
  hero: Props['data']['hero'];
  ctaHref: string;
}) {
  return (
    <HeroFrame
      ariaLabel='Lead Response & Handling hero'
      eyebrow={hero.eyebrow}
      title={hero.title}
      description={hero.description}
      actions={[
        {
          label: 'Request a System Review',
          href: ctaHref,
          variant: 'white',
          icon: <ArrowRight size={16} aria-hidden='true' />,
        },
      ]}
      chips={Array.isArray(hero.list) ? hero.list.map(label => ({ label })) : undefined}
      chipDotVariant='subtle'
      visual={<LeadResponseHandlingSignalPanel visual={hero.visual} />}
    />
  );
}

function LeadResponseHandlingSignalPanel({ visual }: { visual: Props['data']['hero']['visual'] }) {
  if (!visual) return null;

  return (
    <div className='rounded-[var(--mw-radius-2xl)] border border-[var(--mw-white-12)] bg-[var(--mw-white-06)] p-5 shadow-[var(--mw-shadow-dark-lg)]'>
      <div className='mb-5 flex items-start justify-between gap-4 border-b border-[var(--mw-white-10)] pb-4'>
        <div>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>{visual.title}</p>
          <p className='mw-text-on-dark-muted'>{visual.subtitle}</p>
        </div>
        <StatusBadge variant='active' label='Live' />
      </div>

      <div className='grid gap-3'>
        {visual.rows.map(row => {
          const status = String(row.status);
          const Icon =
            status === 'leaking' || status === 'risk'
              ? PhoneOff
              : status === 'unowned' || status === 'warn'
                ? FileText
                : Inbox;
          const badgeVariant =
            status === 'leaking' || status === 'risk'
              ? 'leaking'
              : status === 'unowned' || status === 'warn'
                ? 'unowned'
                : 'handled';

          return (
            <div
              key={row.label}
              className='grid grid-cols-[auto_1fr_auto] items-center gap-3 rounded-[var(--mw-radius-lg)] border border-[var(--mw-white-08)] bg-[var(--mw-white-04)] px-3 py-3'
            >
              <span className='grid size-8 place-items-center rounded-full border border-[var(--mw-white-12)] bg-[var(--mw-white-08)] text-[var(--mw-signal-cyan)]'>
                <Icon size={15} aria-hidden='true' />
              </span>
              <strong className='mw-text-on-dark'>{row.label}</strong>
              <StatusBadge variant={badgeVariant} label={row.value} />
            </div>
          );
        })}
      </div>

      <div className='mt-5 flex flex-wrap items-center gap-3 border-t border-[var(--mw-white-10)] pt-4'>
        <StatusBadge variant='handled' label={visual.footerPrimary} />
        <StatusBadge variant='active' label={visual.footerSecondary} />
      </div>
    </div>
  );
}

