function LeadResponseHandlingFAQ({ faq }: { faq: NonNullable<Props['data']['faq']> }) {
  return (
    <FAQSection
      title={faq.header.title}
      description={faq.header.description}
      items={faq.items.map((item, index) => ({
        id: `smart-website-faq-${index}`,
        question: item.question,
        answer: item.answer,
      }))}
      tone='mist'
      variant='split'
      ariaLabel='Lead Response & Handling FAQ'
    />
  );
}

function LeadResponseHandlingDecisionPanel({ cta }: { cta: Props['data']['cta'] }) {
  return (
    <DecisionPanel
      heading={{
        title: cta.heading.title,
        subtitle: cta.heading.muted,
        description: cta.heading.description,
      }}
      actions={cta.actions}
      expectations={cta.expectations}
      reassurance={cta.footer}
    />
  );
}

export default LeadResponseHandlingRenderer;
