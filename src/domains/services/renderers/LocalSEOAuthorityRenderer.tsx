/**
 * LOCAL SEO AUTHORITY REBUILD BRIEF — MindWP
 *
 * Purpose:
 * Help an established local service business or specialist clinic recognise
 * that being found is only the first step. Nearby customers and patients still
 * need to verify the business or practice, trust what they find, understand the
 * service/treatment/procedure relevance, and move into a clear call, booking,
 * quote, appointment, or consultation path.
 *
 * This page should make clear that Local SEO Authority Systems is not a generic
 * SEO service, ranking package, Google Business Profile hack, citation blast,
 * review-generation service, or traffic-only offer. It is the local discovery,
 * verification, trust, service-area/practice relevance, proof-alignment, and
 * next-step clarity system around the website.
 *
 * Page role:
 * Local SEO Authority Systems is a primary service page and BOFU decision-
 * support page. It owns local discovery, Google Business Profile direction,
 * local search visibility, service-area/location relevance, local trust signals,
 * listing/citation direction where relevant, local proof alignment, and website
 * trust alignment where local conversion depends on it.
 *
 * It may reference Smart Website Systems, Reputation & Review Systems, Lead
 * Response & Handling Systems, and Follow-Up & CRM Systems only where they
 * clarify the local path. It must not absorb website rebuild scope, full review
 * generation, first-response handling, CRM/follow-up lifecycle, or automation.
 *
 * Audience reality:
 * - Home/service businesses: nearby searches, maps, reviews, service areas,
 *   urgent or planned jobs, quote requests, calls, local proof, and trust before
 *   contact.
 * - Specialist clinics: local patient search, provider/practice trust,
 *   treatment/procedure relevance, appointment or consultation paths, reviews,
 *   and proof — without medical claims, treatment-result claims, compliance
 *   claims, EMR/software framing, or generic doctor marketing.
 *
 * Page length and section direction:
 * This should be a substantial service page, not a short SEO landing page. It
 * needs enough depth to reframe local SEO away from rankings, show the find ->
 * verify -> trust -> contact/book path, explain ownership boundaries, connect
 * Google Business Profile and website clarity, show local relevance and proof,
 * filter fit, answer hesitation, and end with a diagnostic CTA.
 *
 * The section sequence below is strategic direction, not a rigid wireframe or
 * final section count. Claude may merge, split, rename, reorder, or reshape
 * sections if the service-page argument becomes stronger, but the final page
 * should still feel complete, premium, commercially serious, and specific to
 * Local SEO Authority Systems.
 *
 * Soft section direction:
 * 1. Hero — Nearby People May Find You. They Still Need to Verify You.
 *    Open with the local decision path, not “we rank your business higher.”
 *    Frame local SEO as find -> verify -> trust -> contact/book.
 *
 * 2. Visibility Alone Does Not Create Local Authority.
 *    Reframe common misconceptions: ranking without relevance, traffic without
 *    trust, GBP without website clarity, reviews without proof placement, and
 *    service areas without a clear next step.
 *
 * 3. Local SEO Starts With the Website, Not Around It.
 *    Carry forward the useful old-page idea. Being found only helps when the
 *    website, local profile, proof, service/treatment clarity, and next step
 *    tell the same story.
 *
 * 4. The Local Path Breaks Between Find, Verify, Trust, and Contact.
 *    Build a local leak map: search, map/listing, website, service/treatment
 *    page, reviews/proof, and call/booking/contact path.
 *
 * 5. What Local SEO Authority Systems Owns.
 *    Define ownership clearly: local discovery, GBP direction, local visibility,
 *    service-area/practice relevance, local trust signals, listing/citation
 *    direction where relevant, proof alignment, and website trust alignment.
 *
 *    Also show what it does not replace: guaranteed rankings, fake authority
 *    signals, full website conversion, full review generation, full lead response
 *    handling, full CRM lifecycle, or disconnected SEO tricks.
 *
 * 6. Google Business Profile and Website Must Tell the Same Story.
 *    Show GBP, services, location/service area, reviews/proof, website pages,
 *    and contact/booking paths working together. Avoid category/post/photo hack
 *    language or local SEO dashboard framing.
 *
 * 7. Service-Area and Practice Relevance Need Structure.
 *    For service businesses, show service area, job type, planned vs urgent
 *    demand, local proof, and quote/contact path. For clinics, show location
 *    relevance, service/treatment/procedure clarity, provider/practice trust,
 *    appointment or consultation path, and careful no-claims language.
 *
 * 8. Reviews and Proof Support Local Trust.
 *    Connect reputation without absorbing it. Local SEO Authority aligns proof
 *    with local trust; Reputation & Review Systems owns the full review request,
 *    feedback routing, and proof-capture system.
 *
 * 9. Local Authority Is Maintained, Not Installed.
 *    Carry forward the useful old-page principle. Show ongoing alignment across
 *    services, locations, profile details, reviews/proof, website clarity, and
 *    practical review — not a generic monthly SEO retainer/process checklist.
 *
 * 10. What Changes When Local Visibility and Trust Are Aligned.
 *     Show operating change without fake metrics: local presence feels
 *     consistent, nearby visitors verify faster, service/practice relevance is
 *     clearer, proof supports trust, and the next step is easier to choose.
 *
 * 11. How This Shows Up in Home Services and Specialist Clinics.
 *     Use realistic scenario cards only if they help: HVAC seasonal search,
 *     plumbing urgent local search, roofing quote trust, foundation repair
 *     high-trust enquiry, dental implant consultation trust, orthodontic parent
 *     research, dermatology appointment trust, or ENT/sinus specialist relevance.
 *     No fake metrics, invented rankings, patient outcomes, or treatment claims.
 *
 * 12. Fit / Not Fit.
 *     Good fit: established local service businesses and specialist clinics with
 *     real search activity or local competition, service-area/location relevance,
 *     reviews/proof sensitivity, website-local mismatch, or maintained authority
 *     needs.
 *
 *     Not fit: guaranteed-ranking buyers, cheap citation-blast buyers, fake
 *     review seekers, “dominate Google” expectations, one-time SEO hack buyers,
 *     businesses with no service/practice clarity, tool-dashboard buyers, or
 *     healthcare buyers expecting software/compliance/treatment outcome claims.
 *
 * 13. FAQ.
 *     Use FAQ only for real buying hesitation: whether this is the same as SEO,
 *     whether rankings are guaranteed, how GBP fits, whether website pages need
 *     work first, how reviews connect, how this works for clinics, and whether
 *     local authority is ongoing or one-time. Avoid result timelines unless they
 *     are framed carefully and without promises.
 *
 * 14. Final Diagnostic CTA.
 *     Close with a practical review of the local visibility and trust path. The
 *     CTA should feel useful and diagnostic, not like a ranking pitch, SEO audit
 *     gimmick, sales push, package quote, dashboard demo, or generic contact form.
 *
 * Component and content guidance:
 * - Use HeroFrame for the service hero if it helps the page argument.
 * - Use SectionShell as the outer wrapper for major sections where useful.
 * - Use page-owned JSX for find-verify-trust-contact paths, local leak maps,
 *   local signal boards, GBP-to-website alignment panels, service-area/practice
 *   relevance maps, local proof stacks, ownership boundaries, maintained-
 *   authority cycles, before/after operating states, scenario boards, and fit
 *   filters.
 * - Do not force all section content into the data file while the page is being
 *   proven. Hero, FAQ, and DecisionPanel content may stay in data if useful.
 * - Use DecisionPanel for the final diagnostic CTA if it fits.
 * - Use FAQSection only if the questions answer real buying hesitation.
 * - Do not let old renderer order, existing data shape, or reusable components
 *   force generic SEO cards, technical checklists, ranking dashboards, process
 *   steps, or weak section rhythm.
 *
 * Visual direction:
 * Calm, premium, operational, specific, and commercially serious. Use find ->
 * verify -> trust -> contact paths, local signal boards, GBP-to-website
 * alignment surfaces, service-area/practice relevance maps, local proof stacks,
 * ownership maps, maintained-authority cycles, before/after local authority
 * panels, selective scenario/proof surfaces, fit filters, and diagnostic CTA
 * panels.
 *
 * This page should feel visually distinct from Smart Website Systems. SWS uses
 * website-control maps, service-page anatomy, handoff paths, and implementation
 * pathways. Local SEO Authority should use local discovery, verification, trust,
 * profile/website alignment, service-area relevance, and proof signals.
 *
 * Selective imagery is allowed when it supports business meaning. Avoid random
 * stock photos, fake dashboards, SaaS UI, AI robot visuals, generic laptop
 * mockups, decorative charts, generic SEO ranking dashboards, citation-grid
 * filler, and image-heavy gallery behavior.
 *
 * CTA posture:
 * Diagnostic, low-pressure, practical.
 *
 * Good directions:
 * - Review my local visibility
 * - Check my local trust path
 * - Find where local enquiries are leaking
 * - Request a local authority review
 *
 * Simple UI labels may work only when nearby copy explains the diagnostic value.
 *
 * Avoid:
 * Generic SEO agency page, guaranteed-rankings page, “dominate Google” language,
 * traffic-only service page, citation/link-building checklist, GBP hack page,
 * review-generation page, local SEO dashboard imitation, full website rebuild
 * page, generic contractor marketing, generic doctor marketing, fake proof, fake
 * metrics, unsupported medical/treatment claims, and old renderer order.
 *
 * Rebuild instruction:
 * Existing JSX and old Local SEO content are context only. Preserve useful
 * intent, not old structure. The old page had useful ideas — local SEO starts
 * with the website, visibility is maintained not installed, SEO disappointment
 * often hides a structure problem, integration with the wider path, fit filter,
 * and FAQ — but it leaned too far toward ongoing SEO service, technical
 * checklists, reporting/process language, and generic SEO scope. Carry forward
 * the good ideas in the current MindWP language.
 *
 * First create the render shape: HeroFrame setup, SectionShell sequence,
 * section titles/descriptions/tone, CTA placement, and any needed custom class
 * or background-treatment decisions.
 *
 * Then design the inner section content with page-owned JSX.
 *
 * Since this is one of the first three baseline pages, shared component, token,
 * or CSS improvements are allowed only when clearly justified by the Local SEO
 * Authority design direction. Report page-owned changes, shared component
 * changes, token/CSS changes, and design-system implications separately.
 */
import { ArrowRight, FileText, Inbox, PhoneOff } from 'lucide-react';

import { FAQSection } from '@/components/content/FAQSection';
import { DecisionPanel } from '@/components/conversion/DecisionPanel';
import { HeroFrame } from '@/components/layout/HeroFrame';
import { SectionShell } from '@/components/layout/SectionShell';
import { StatusBadge } from '@/components/primitives/StatusBadge';
import type { ServicePageData } from '@/domains/services/types';

interface Props {
  data: ServicePageData;
  slug: string;
}

export default function LocalSEOAuthorityRenderer({ data }: Props) {
  const { hero, cta } = data;
  const faq = data.faq;

  return (
    <main>
      <LocalSeoAuthorityHero hero={hero} ctaHref={cta.actions[0]?.href ?? '/contact'} />
      <LocalSeoAuthorityRecognitionSection />
      {faq ? <LocalSeoAuthorityFAQ faq={faq} /> : null}
      <LocalSeoAuthorityDecisionPanel cta={cta} />
    </main>
  );
}

function LocalSeoAuthorityHero({
  hero,
  ctaHref,
}: {
  hero: Props['data']['hero'];
  ctaHref: string;
}) {
  return (
    <HeroFrame
      ariaLabel='Local SEO Authority hero'
      eyebrow={hero.eyebrow}
      title={hero.title}
      description={hero.description}
      actions={[
        {
          label: 'Request a System Review',
          href: ctaHref,
          variant: 'white',
          icon: <ArrowRight size={16} aria-hidden='true' />,
        },
      ]}
      chips={Array.isArray(hero.list) ? hero.list.map(label => ({ label })) : undefined}
      chipDotVariant='subtle'
      visual={<LocalSeoAuthoritySignalPanel visual={hero.visual} />}
    />
  );
}

function LocalSeoAuthoritySignalPanel({ visual }: { visual: Props['data']['hero']['visual'] }) {
  if (!visual) return null;

  return (
    <div className='rounded-[var(--mw-radius-2xl)] border border-[var(--mw-white-12)] bg-[var(--mw-white-06)] p-5 shadow-[var(--mw-shadow-dark-lg)]'>
      <div className='mb-5 flex items-start justify-between gap-4 border-b border-[var(--mw-white-10)] pb-4'>
        <div>
          <p className='mw-text-eyebrow mw-text-signal-cyan'>{visual.title}</p>
          <p className='mw-text-on-dark-muted'>{visual.subtitle}</p>
        </div>
        <StatusBadge variant='active' label='Live' />
      </div>

      <div className='grid gap-3'>
        {visual.rows.map(row => {
          const status = String(row.status);
          const Icon =
            status === 'leaking' || status === 'risk'
              ? PhoneOff
              : status === 'unowned' || status === 'warn'
                ? FileText
                : Inbox;
          const badgeVariant =
            status === 'leaking' || status === 'risk'
              ? 'leaking'
              : status === 'unowned' || status === 'warn'
                ? 'unowned'
                : 'handled';

          return (
            <div
              key={row.label}
              className='grid grid-cols-[auto_1fr_auto] items-center gap-3 rounded-[var(--mw-radius-lg)] border border-[var(--mw-white-08)] bg-[var(--mw-white-04)] px-3 py-3'
            >
              <span className='grid size-8 place-items-center rounded-full border border-[var(--mw-white-12)] bg-[var(--mw-white-08)] text-[var(--mw-signal-cyan)]'>
                <Icon size={15} aria-hidden='true' />
              </span>
              <strong className='mw-text-on-dark'>{row.label}</strong>
              <StatusBadge variant={badgeVariant} label={row.value} />
            </div>
          );
        })}
      </div>

      <div className='mt-5 flex flex-wrap items-center gap-3 border-t border-[var(--mw-white-10)] pt-4'>
        <StatusBadge variant='handled' label={visual.footerPrimary} />
        <StatusBadge variant='active' label={visual.footerSecondary} />
      </div>
    </div>
  );
}

