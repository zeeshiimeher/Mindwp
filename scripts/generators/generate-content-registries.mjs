#!/usr/bin/env node

import fs from 'node:fs';
import path from 'node:path';

const root = process.cwd();
const srcRoot = path.join(root, 'src');

const BLOG_CONTENT_DIR = path.join(srcRoot, 'domains', 'blog', 'content');
const BLOG_REGISTRY_FILE = path.join(srcRoot, 'domains', 'blog', 'registry.ts');

const RESOURCE_CONTENT_DIR = path.join(srcRoot, 'domains', 'resources', 'content');
const RESOURCE_GENERATED_REGISTRY_FILE = path.join(
  srcRoot,
  'domains',
  'resources',
  'generatedRegistry.ts'
);

const CASE_STUDY_CONTENT_DIR = path.join(srcRoot, 'domains', 'case-studies', 'content');
const CASE_STUDY_REGISTRY_FILE = path.join(srcRoot, 'domains', 'case-studies', 'registry.ts');

const toImportPath = filePath => {
  const rel = path
    .relative(path.join(srcRoot, 'domains'), filePath)
    .replace(/\\/g, '/')
    .replace(/\.tsx?$/, '');

  return `@/domains/${rel}`;
};

const readTsxFiles = dir => {
  if (!fs.existsSync(dir)) return [];
  return fs
    .readdirSync(dir, { withFileTypes: true })
    .filter(entry => entry.isFile() && entry.name.endsWith('.tsx'))
    .map(entry => path.join(dir, entry.name));
};

const parseSlug = text => {
  const slugConst = /const\s+slug\s*=\s*['"]([^'"]+)['"]/.exec(text)?.[1];
  if (slugConst) return slugConst;

  return /\bslug\s*:\s*['"]([^'"]+)['"]/.exec(text)?.[1] ?? null;
};

const parseTypedConst = (text, typeName) => {
  return new RegExp(`export\\s+const\\s+(\\w+)\\s*:\\s*${typeName}`).exec(text)?.[1] ?? null;
};

const writeIfChanged = (filePath, content) => {
  const existing = fs.existsSync(filePath) ? fs.readFileSync(filePath, 'utf8') : null;
  if (existing === content) return false;
  fs.writeFileSync(filePath, content, 'utf8');
  return true;
};

const buildRegistryFile = ({ entries, typeImport, typeName, registryConst, listConst, header }) => {
  const sortedEntries = [...entries].sort((a, b) => a.slug.localeCompare(b.slug));

  const importLines = sortedEntries.map(
    entry => `import { ${entry.constName} } from '${entry.importPath}';`
  );
  const objectLines = sortedEntries.map(entry => `  '${entry.slug}': ${entry.constName},`);

  return [
    header,
    ...importLines,
    `import type { ${typeName} } from '${typeImport}';`,
    '',
    `export const ${registryConst}: Record<string, ${typeName}> = {`,
    ...objectLines,
    '};',
    '',
    `export const ${listConst} = Object.values(${registryConst});`,
    '',
  ].join('\n');
};

const generateBlogRegistry = () => {
  const entries = readTsxFiles(BLOG_CONTENT_DIR)
    .map(filePath => {
      const text = fs.readFileSync(filePath, 'utf8');
      const constName = parseTypedConst(text, 'BlogPostData');
      const slug = parseSlug(text);
      if (!constName || !slug) return null;

      return {
        constName,
        slug,
        importPath: toImportPath(filePath),
      };
    })
    .filter(Boolean);

  const content = buildRegistryFile({
    entries,
    typeImport: '@/domains/blog/types',
    typeName: 'BlogPostData',
    registryConst: 'BLOG_POSTS',
    listConst: 'blogPosts',
    header: '// AUTO-GENERATED by scripts/generate-content-registries.mjs. Do not edit manually.',
  });

  return writeIfChanged(BLOG_REGISTRY_FILE, content);
};

const generateResourcesRegistry = () => {
  const entries = readTsxFiles(RESOURCE_CONTENT_DIR)
    .map(filePath => {
      const text = fs.readFileSync(filePath, 'utf8');
      const constName = parseTypedConst(text, 'ResourceData');
      const slug = parseSlug(text);
      if (!constName || !slug) return null;

      return {
        constName,
        slug,
        importPath: toImportPath(filePath),
      };
    })
    .filter(Boolean);

  const content = buildRegistryFile({
    entries,
    typeImport: '@/domains/resources/types',
    typeName: 'ResourceData',
    registryConst: 'RESOURCE_REGISTRY',
    listConst: 'resources',
    header: '// AUTO-GENERATED by scripts/generate-content-registries.mjs. Do not edit manually.',
  });

  return writeIfChanged(RESOURCE_GENERATED_REGISTRY_FILE, content);
};

const generateCaseStudyRegistry = () => {
  const entries = readTsxFiles(CASE_STUDY_CONTENT_DIR)
    .map(filePath => {
      const text = fs.readFileSync(filePath, 'utf8');
      const constName = parseTypedConst(text, 'CaseStudyData');
      const slug = parseSlug(text);
      if (!constName || !slug) return null;

      return {
        constName,
        slug,
        importPath: toImportPath(filePath),
      };
    })
    .filter(Boolean);

  const content = buildRegistryFile({
    entries,
    typeImport: '@/domains/case-studies/types',
    typeName: 'CaseStudyData',
    registryConst: 'CASE_STUDY_REGISTRY',
    listConst: 'caseStudies',
    header: '// AUTO-GENERATED by scripts/generate-content-registries.mjs. Do not edit manually.',
  });

  return writeIfChanged(CASE_STUDY_REGISTRY_FILE, content);
};

const changed = [
  generateBlogRegistry(),
  generateResourcesRegistry(),
  generateCaseStudyRegistry(),
].filter(Boolean).length;

// eslint-disable-next-line no-console
console.log(`✅ Content registries generated (${changed} file(s) changed).`);
